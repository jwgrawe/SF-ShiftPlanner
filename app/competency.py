"""Competency data: the matrix, Excel in and out, name linking (D96–D99).

The app's own copy (the master, once the department switches over) is
`competency_rows`, keyed by the person's name exactly as the exports write it
(D82); in demo mode the seed's `employee_competencies` is edited directly.

Values: 'qualified' («Ja»), 'uncertain' («Ukjent» — never eligible, D44) and
'' (no competency; blank or «Nei» in a file).

Excel never writes straight into the data. A file is *staged*; the review
links unknown names to people (suggesting likely matches — written for the
department's abbreviated-name list), then shows exactly what would change and
asks before anything already filled in is overwritten. A form generated by
the app carries a hidden copy of the values it started from, so on import
only cells the person filling it in actually changed are applied (three-way
merge): an old form can never undo newer edits.
"""
from __future__ import annotations

import datetime as dt
import io
import json
import re
import sqlite3
import unicodedata
from collections import defaultdict

from app import applog, db
from app.hr_export import Rejected, norm

STANDARD_KEY = "__standard__"
BASE_SHEET = "Grunnlag"
GUIDE_SHEET = "Slik fyller du ut"
MAIN_SHEET = "Kompetanse"
EXTRA_COLUMNS = {"stilling", "stillingsbetegnelse", "merknad", "kommentar"}
WORDS = {"qualified": "Ja", "uncertain": "Ukjent", "": "Nei"}
ZONE_FILLS = {"uren": "B25F4D", "ren": "4877AB", "steril": "54876A", "utpost": "9C7A3D"}


def word(status: str) -> str:
    return WORDS.get(status or "", status)


def parse_mark(value) -> tuple[str | None, bool]:
    """A cell from a workbook -> (status, understood)."""
    text = "" if value is None else str(value).strip().lower()
    if text in ("", "nei", "n", "no", "-", "–"):
        return "", True
    if text in ("ja", "j", "x", "yes"):
        return "qualified", True
    if text in ("ukjent", "?", "u"):
        return "uncertain", True
    return None, False


# ---------------------------------------------------------------- columns
def columns(conn: sqlite3.Connection) -> list[dict]:
    """The matrix columns, as in the workbook: one per source column (a
    combined column such as «Sterrad + poliklinikker/løspakk» sets both of
    its competencies), grouped by zone."""
    zone_of: dict[str, tuple[str, str, int]] = {}
    for row in conn.execute(
            """SELECT fc.competency_id, z.zone_id, z.name, z.sort_order FROM function_competencies fc
               JOIN functions f ON f.function_id = fc.function_id
               JOIN zones z ON z.zone_id = f.zone_id ORDER BY fc.priority, f.sort_order"""):
        zone_of.setdefault(row["competency_id"], (row["zone_id"], row["name"], row["sort_order"]))
    cols: dict[str, dict] = {}
    for row in conn.execute("SELECT rowid, * FROM competency_types ORDER BY rowid"):
        label = norm(row["source_column"] or row["name"])
        col = cols.setdefault(label, {
            "key": label, "label": label, "ids": [],
            "zone": zone_of.get(row["competency_id"], ("", "", 99)),
        })
        col["ids"].append(row["competency_id"])
    result = list(cols.values())
    for col in result:
        zone_id, zone_name, _ = col.pop("zone")
        col["zone_id"], col["zone_name"] = zone_id, zone_name
    return result


# ------------------------------------------------------------- the matrix
def _values_by(conn, sql: str, params=()) -> dict[str, dict[str, str]]:
    by_id: dict[str, dict[str, str]] = defaultdict(dict)
    for row in conn.execute(sql, params):
        by_id[row[0]][row[1]] = row[2]
    return by_id


def current_values(conn: sqlite3.Connection) -> dict[str, dict[str, str]]:
    """key -> column -> status, for every person with data, plus the
    standard row under STANDARD_KEY."""
    cols = columns(conn)
    if db.is_demo():
        raw = _values_by(conn, "SELECT employee_id, competency_id, status FROM employee_competencies")
    else:
        raw = _values_by(conn, "SELECT full_name, competency_id, status FROM competency_rows")
    raw[STANDARD_KEY] = {r["competency_id"]: r["status"] for r in conn.execute(
        "SELECT competency_id, status FROM standard_competencies")}
    values: dict[str, dict[str, str]] = {}
    for key, by_competency in raw.items():
        values[key] = {}
        for col in cols:
            status = next((by_competency[c] for c in col["ids"] if c in by_competency), "")
            if status:
                values[key][col["key"]] = status
    return values


def people(conn: sqlite3.Connection) -> list[dict]:
    """Everyone the matrix should show: in real mode the people in the
    active turnus and ukeplans (temps — only in an ukeplan — flagged), in
    demo mode the seed staff."""
    if db.is_demo():
        return [
            {"key": r["employee_id"], "full_name": f"{r['last_name']} {r['first_name']}",
             "display": r["display_name"], "title": "", "temp": False}
            for r in conn.execute(
                "SELECT * FROM employees WHERE works_at = 'sf' ORDER BY last_name, first_name")
        ]
    titles: dict[str, str] = {}
    for r in conn.execute(
            """SELECT r.full_name, r.title FROM import_rows r
               JOIN import_files f ON f.file_id = r.file_id
               WHERE f.kind = 'plan' AND f.status = 'active'
               ORDER BY f.exported_at, r.last_date"""):
        if r["title"]:
            titles[r["full_name"]] = r["title"]
    present = {r[0] for r in conn.execute(
        """SELECT DISTINCT r.full_name FROM import_rows r JOIN import_files f ON f.file_id = r.file_id
           WHERE f.status = 'active' AND f.kind IN ('plan', 'ajourhold')""")}
    found = []
    for r in conn.execute("SELECT * FROM employees WHERE origin = 'import'"):
        if r["full_name"] in present:
            found.append({"key": r["full_name"], "full_name": r["full_name"],
                          "display": r["display_name"], "title": titles.get(r["full_name"], ""),
                          "temp": bool(r["is_temp"])})
    found.sort(key=lambda p: (p["temp"], p["full_name"].lower()))
    return found


def matrix(conn: sqlite3.Connection) -> dict:
    cols = columns(conn)
    values = current_values(conn)
    rows = []
    for person in people(conn):
        mine = values.get(person["key"], {})
        rows.append({**person, "values": mine,
                     "empty": not mine, "unknown": sum(1 for v in mine.values() if v == "uncertain")})
    shown = {p["key"] for p in rows}
    orphans = [] if db.is_demo() else sorted(
        k for k in values if k not in shown and k != STANDARD_KEY)
    temps = sum(1 for r in rows if r["temp"])
    titles = sorted({r["title"] for r in rows if r["title"]})
    return {"columns": cols, "rows": rows, "standard": values.get(STANDARD_KEY, {}),
            "orphans": orphans, "temps": temps, "titles": titles,
            "zones": _zone_spans(cols)}


def _zone_spans(cols: list[dict]) -> list[dict]:
    spans: list[dict] = []
    for col in cols:
        if spans and spans[-1]["zone_id"] == col["zone_id"]:
            spans[-1]["span"] += 1
        else:
            spans.append({"zone_id": col["zone_id"], "name": col["zone_name"], "span": 1})
    return spans


def _write(conn: sqlite3.Connection, key: str, col: dict, status: str) -> None:
    for competency_id in col["ids"]:
        if key == STANDARD_KEY:
            conn.execute("DELETE FROM standard_competencies WHERE competency_id = ?", (competency_id,))
            if status:
                conn.execute("INSERT INTO standard_competencies VALUES (?, ?)", (competency_id, status))
        elif db.is_demo():
            conn.execute("DELETE FROM employee_competencies WHERE employee_id = ? AND competency_id = ?",
                         (key, competency_id))
            if status:
                conn.execute("INSERT INTO employee_competencies (employee_id, competency_id, status) "
                             "VALUES (?, ?, ?)", (key, competency_id, status))
        else:
            conn.execute("DELETE FROM competency_rows WHERE full_name = ? AND competency_id = ?",
                         (key, competency_id))
            if status:
                conn.execute("INSERT INTO competency_rows VALUES (?, ?, ?)", (key, competency_id, status))


def _label(conn: sqlite3.Connection, key: str) -> str:
    if key == STANDARD_KEY:
        return "Standardkompetanse for vikarer"
    if db.is_demo():
        row = conn.execute("SELECT display_name FROM employees WHERE employee_id = ?", (key,)).fetchone()
        return row[0] if row else key
    return key


def apply_changes(conn: sqlite3.Connection, changes: list[dict]) -> tuple[int, list[str]]:
    """Save edits from the matrix. Each change carries the value the editor
    saw (`old`); a cell changed by someone else meanwhile is not touched and
    is reported instead (optimistic locking — no lost updates)."""
    cols = {c["key"]: c for c in columns(conn)}
    current = current_values(conn)
    applied, conflicts = 0, []
    with conn:
        for change in changes:
            key, col_key = str(change.get("key", "")), str(change.get("col", ""))
            old, new = str(change.get("old") or ""), str(change.get("new") or "")
            col = cols.get(col_key)
            if col is None or new not in WORDS or old not in WORDS or not key:
                continue
            now = current.get(key, {}).get(col_key, "")
            if now != old:
                conflicts.append(f"{_label(conn, key)} / {col_key}: endret av noen andre i mellomtiden "
                                 f"(nå «{word(now)}») – ikke lagret.")
                continue
            if now == new:
                continue
            _write(conn, key, col, new)
            applog.log(conn, "kompetanse", f"{_label(conn, key)}: {col_key} {word(now)} → {word(new)}")
            applied += 1
    return applied, conflicts


def remove_person(conn: sqlite3.Connection, key: str) -> None:
    """Drop all competency data for a name no longer in turnus/ukeplan."""
    with conn:
        conn.execute("DELETE FROM competency_rows WHERE full_name = ?", (key,))
        applog.log(conn, "kompetanse", f"{key}: all kompetanse fjernet (ikke i turnus/ukeplan).")


# ------------------------------------------------------------- Excel in
def _find_header(rows: list[list[str]], known: set[str]) -> int | None:
    for i, row in enumerate(rows[:15]):
        if sum(1 for c in row[1:] if norm(c).lower() in known) >= 3:
            return i
    return None


def _sheet_rows(ws) -> list[list[str]]:
    return [["" if c is None else str(c) for c in r] for r in ws.iter_rows(values_only=True)]


def read_workbook(conn: sqlite3.Connection, raw: bytes) -> dict:
    """Parse a competency workbook (today's layout: names in column A,
    competencies as columns under a heading row). Raises Rejected."""
    from openpyxl import load_workbook

    try:
        wb = load_workbook(io.BytesIO(raw), data_only=True)
    except Exception as exc:  # noqa: BLE001 - any unreadable workbook
        raise Rejected([f"Regnearket kan ikke åpnes ({exc.__class__.__name__})."]) from None
    cols = columns(conn)
    known = {c["key"].lower(): c["key"] for c in cols}

    def grid(ws, strict: bool) -> tuple[dict, list[str], list[str]]:
        rows = _sheet_rows(ws)
        header_index = _find_header(rows, set(known))
        if header_index is None:
            if strict:
                raise Rejected(["Fant ingen overskriftsrad med kompetansene som kolonner – er dette "
                                "kompetansefilen?"])
            return {}, [], []
        header = [norm(c) for c in rows[header_index]]
        unknown = [h for h in header[1:] if h and h.lower() not in known
                   and h.lower() not in EXTRA_COLUMNS]
        if unknown and strict:
            raise Rejected([f"Ukjente kolonner: {unknown}. Kompetansekolonnene må hete som i appen "
                            f"({', '.join(c['key'] for c in cols)})."])
        result: dict[str, dict[str, str]] = {}
        notes: list[str] = []
        duplicates = []
        for r in rows[header_index + 1:]:
            name = norm(r[0]) if r else ""
            if not name:
                continue
            if name in result:
                duplicates.append(name)
                continue
            values = {}
            for value, label in zip(r[1:], header[1:]):
                key = known.get(label.lower())
                if not key:
                    continue
                status, ok = parse_mark(value)
                if not ok:
                    notes.append(f"{name} / {key}: «{value}» forstås ikke – cellen endres ikke "
                                 "(bruk Ja, Ukjent eller tomt).")
                    continue
                values[key] = status
            result[name] = values
        if duplicates and strict:
            raise Rejected([f"Samme navn står flere ganger: {', '.join(sorted(set(duplicates)))}."])
        present = [known[h.lower()] for h in header[1:] if h and h.lower() in known]
        return result, notes, present

    main = next((ws for ws in wb.worksheets
                 if ws.title not in (BASE_SHEET, GUIDE_SHEET) and ws.sheet_state == "visible"
                 and _find_header(_sheet_rows(ws), set(known)) is not None), None)
    if main is None:
        raise Rejected(["Fant ikke kompetansearket – ingen fane har en overskriftsrad med "
                        "kompetansene som kolonner."])
    rows, notes, present = grid(main, strict=True)
    if not rows:
        raise Rejected(["Kompetansearket har ingen navn."])
    missing = [c["key"] for c in cols if c["key"] not in present]
    if missing:
        notes.insert(0, f"Kolonnene {', '.join(missing)} mangler i filen – de endres ikke.")
    base = None
    generated = None
    if BASE_SHEET in wb.sheetnames:
        base, _, _ = grid(wb[BASE_SHEET], strict=False)
        stamp = wb[BASE_SHEET]["A1"].value
        generated = str(stamp) if stamp else None
    return {"rows": rows, "base": base, "notes": notes, "columns": present,
            "generated": generated}


def stage(conn: sqlite3.Connection, filename: str, raw: bytes) -> int:
    """Keep a parsed workbook for review. Raises Rejected."""
    from app.hr_export import sha256

    parsed = read_workbook(conn, raw)
    cursor = conn.execute(
        "INSERT INTO competency_imports (filename, sha256, uploaded_at, status, payload) "
        "VALUES (?, ?, ?, 'venter', ?)",
        (filename, sha256(raw), dt.datetime.now().isoformat(timespec="seconds"),
         json.dumps(parsed, ensure_ascii=False)))
    applog.log(conn, "kompetanse", f"{filename}: kompetansefil lagt til gjennomgang "
                                   f"({len(parsed['rows'])} navn).")
    return cursor.lastrowid


# ---------------------------------------------------------- name linking
def _tokens(name: str) -> list[str]:
    text = unicodedata.normalize("NFKC", name).lower()
    return [t.strip(".") for t in re.split(r"[\s,]+", text) if t.strip(".")]


def _token_score(a: str, b: str) -> float:
    if a == b:
        return 1.0
    if "-" in b and a in b.split("-"):
        return 0.8
    if b.startswith(a):                      # abbreviation: «Kr» of «Kristine», «K» of «Kari»
        return 0.75 if len(a) >= 2 else 0.55
    if len(b) >= 2 and a.startswith(b):
        return 0.5
    return 0.0


def name_score(alias: str, candidate: str) -> float:
    """How well a (possibly abbreviated, any-order) name fits an export name."""
    a_tokens, c_tokens = _tokens(alias), _tokens(candidate)
    if not a_tokens or not c_tokens:
        return 0.0
    used: set[int] = set()
    total = 0.0
    for a in sorted(a_tokens, key=len, reverse=True):
        best, best_j = 0.0, None
        for j, c in enumerate(c_tokens):
            if j in used:
                continue
            score = _token_score(a, c)
            if score > best:
                best, best_j = score, j
        if best_j is not None:
            used.add(best_j)
        total += best
    score = total / len(a_tokens)
    coverage = len(used) / len(c_tokens)
    surname = 0.05 if 0 in used else 0.0         # exports put the surname first
    return round(min(1.0, 0.85 * score + 0.15 * coverage + surname), 3)


def link_suggestions(aliases: list[str], candidates: list[str]) -> dict[str, dict]:
    """For each unmatched name: ranked candidates and a preselected one.
    Preselection is one-to-one (best pairs first) so a bulk confirm never
    sends two names to the same person."""
    ranked = {a: sorted(((c, name_score(a, c)) for c in candidates), key=lambda x: -x[1])
              for a in aliases}
    pairs = sorted(((s, a, c) for a, lst in ranked.items() for c, s in lst if s >= 0.45),
                   reverse=True)
    chosen: dict[str, str] = {}
    taken: set[str] = set()
    for score, alias, cand in pairs:
        if alias in chosen or cand in taken:
            continue
        chosen[alias] = cand
        taken.add(cand)
    result = {}
    for alias, lst in ranked.items():
        pick = chosen.get(alias)
        top = lst[0][1] if lst else 0.0
        second = lst[1][1] if len(lst) > 1 else 0.0
        pick_score = dict(lst).get(pick, 0.0) if pick else 0.0
        if pick and pick_score >= 0.75 and pick == lst[0][0] and top - second >= 0.15:
            confidence = "sikker"
        elif pick:
            confidence = "usikker"
        else:
            confidence = "ingen"
        result[alias] = {"choice": pick, "confidence": confidence,
                         "options": [c for c, s in lst if s > 0][:8]}
    return result


# ------------------------------------------------------------- the review
def _load(conn: sqlite3.Connection, import_id: int) -> tuple[sqlite3.Row, dict]:
    row = conn.execute("SELECT * FROM competency_imports WHERE import_id = ?", (import_id,)).fetchone()
    if row is None:
        raise KeyError(import_id)
    return row, json.loads(row["payload"])


def candidates(conn: sqlite3.Connection) -> list[str]:
    names = {p["key"] for p in people(conn)}
    names |= {r[0] for r in conn.execute("SELECT DISTINCT full_name FROM competency_rows")}
    return sorted(names)


def review(conn: sqlite3.Connection, import_id: int) -> dict:
    """What an import would do. Step 'link' while names are unresolved,
    then step 'diff' with every change, overwrite and conflict."""
    row, data = _load(conn, import_id)
    known = set(candidates(conn))
    aliases = {r["alias"]: r["full_name"] for r in conn.execute("SELECT * FROM competency_aliases")}
    targets: dict[str, str | None] = {}
    unresolved = []
    for name in data["rows"]:
        if name in known:
            targets[name] = name
        elif name in aliases:
            targets[name] = aliases[name]          # None = skip by choice
        else:
            unresolved.append(name)
    model = {"import": row, "filename": row["filename"], "notes": data["notes"],
             "has_base": data["base"] is not None, "generated": data.get("generated"),
             "status": row["status"], "names_in_file": len(data["rows"])}
    if unresolved:
        suggestions = link_suggestions(unresolved, sorted(known))
        order = {"ingen": 0, "usikker": 1, "sikker": 2}   # the ones needing a look first
        unresolved.sort(key=lambda a: (order[suggestions[a]["confidence"]], a.lower()))
        model.update(step="link", unresolved=unresolved, suggestions=suggestions,
                     candidates=sorted(known))
        return model

    current = current_values(conn)
    base = data["base"]
    per_person: list[dict] = []
    counts = defaultdict(int)
    for name, values in data["rows"].items():
        target = targets.get(name)
        if not target:
            counts["hoppet over"] += 1
            continue
        cur_row = current.get(target, {})
        base_row = base.get(name) if base is not None else None
        changes = []
        for col, new in values.items():
            cur = cur_row.get(col, "")
            if base_row is not None:
                b = base_row.get(col, "")
                if new == b:
                    continue                          # untouched in the form
                if cur != b and cur != new:
                    changes.append({"col": col, "old": cur, "new": new, "kind": "konflikt",
                                    "base": b})
                    counts["konflikt"] += 1
                    continue
            if new == cur:
                continue
            kind = "ny" if cur == "" else "overskriver"
            changes.append({"col": col, "old": cur, "new": new, "kind": kind})
            counts[kind] += 1
        if changes:
            per_person.append({"name": name, "target": target, "changes": changes,
                               "linked": name != target})
    per_person.sort(key=lambda p: p["target"].lower())
    model.update(step="diff", people=per_person, counts=dict(counts),
                 linked={n: t for n, t in targets.items() if t and n != t})
    return model


def save_links(conn: sqlite3.Connection, choices: dict[str, str]) -> list[str]:
    """choices: file name -> export name, '__skip__' or '__keep__'.
    Returns problems; nothing is saved if there are any."""
    known = set(candidates(conn))
    chosen = [t for t in choices.values() if t not in ("__skip__", "__keep__", "")]
    problems = []
    for target in sorted({t for t in chosen if chosen.count(t) > 1}):
        problems.append(f"«{target}» er valgt for flere navn i filen.")
    for alias, target in choices.items():
        if target == "":
            problems.append(f"Velg en person, «behold navnet» eller «hopp over» for «{alias}».")
        elif target not in ("__skip__", "__keep__") and target not in known:
            problems.append(f"«{target}» finnes ikke.")
    if problems:
        return problems
    with conn:
        for alias, target in choices.items():
            value = None if target == "__skip__" else alias if target == "__keep__" else target
            conn.execute("INSERT OR REPLACE INTO competency_aliases VALUES (?, ?, ?)",
                         (alias, value, dt.datetime.now().isoformat(timespec="seconds")))
            what = ("hoppes over" if value is None else "beholdes som eget navn" if value == alias
                    else f"koblet til «{value}»")
            applog.log(conn, "kompetanse", f"Navnet «{alias}» i kompetansefiler {what}.")
    return []


def apply_import(conn: sqlite3.Connection, import_id: int, overwrite_conflicts: bool) -> int:
    model = review(conn, import_id)
    if model["step"] != "diff" or model["status"] != "venter":
        return 0
    cols = {c["key"]: c for c in columns(conn)}
    written = 0
    with conn:
        for person in model["people"]:
            for change in person["changes"]:
                if change["kind"] == "konflikt" and not overwrite_conflicts:
                    continue
                _write(conn, person["target"], cols[change["col"]], change["new"])
                applog.log(conn, "kompetanse",
                           f"{person['target']}: {change['col']} {word(change['old'])} → "
                           f"{word(change['new'])} (fra {model['filename']})")
                written += 1
        conn.execute("UPDATE competency_imports SET status = 'brukt', decided_at = ? "
                     "WHERE import_id = ?", (dt.datetime.now().isoformat(timespec="seconds"), import_id))
        applog.log(conn, "kompetanse", f"{model['filename']}: {written} celler oppdatert.")
    return written


def discard_import(conn: sqlite3.Connection, import_id: int) -> None:
    with conn:
        row = conn.execute("SELECT filename FROM competency_imports WHERE import_id = ?",
                           (import_id,)).fetchone()
        conn.execute("UPDATE competency_imports SET status = 'forkastet', decided_at = ? "
                     "WHERE import_id = ?", (dt.datetime.now().isoformat(timespec="seconds"), import_id))
        if row:
            applog.log(conn, "kompetanse", f"{row['filename']}: forkastet uten endringer.")


def pending_imports(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    return list(conn.execute(
        "SELECT * FROM competency_imports WHERE status = 'venter' ORDER BY import_id DESC"))


