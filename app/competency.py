def build_form(conn: sqlite3.Connection) -> bytes:
    """The fill-in form: every regular employee (temps get the standard set),
    names exactly as exported, current values pre-filled, dropdowns, colours,
    locked structure, and a hidden copy of the starting values."""
    from openpyxl import Workbook
    from openpyxl.formatting.rule import CellIsRule
    from openpyxl.styles import Alignment, Font, PatternFill, Protection
    from openpyxl.utils import get_column_letter
    from openpyxl.worksheet.datavalidation import DataValidation

    data = matrix(conn)
    cols = data["columns"]
    rows = [r for r in data["rows"] if not r["temp"]]
    stamp = f"Generert {dt.datetime.now():%d.%m.%Y %H:%M} av SF-Planlegger"

    wb = Workbook()
    guide = wb.active
    guide.title = GUIDE_SHEET
    for i, line in enumerate(GUIDE, start=1):
        guide.cell(row=i, column=1, value=line)
    guide["A1"].font = Font(bold=True, size=14)
    guide.column_dimensions["A"].width = 100

    def fill_grid(ws, with_style: bool) -> None:
        ws.cell(row=1, column=1, value=stamp if not with_style else None)
        col = 2
        for zone in data["zones"]:
            cell = ws.cell(row=1, column=col, value=zone["name"])
            if with_style:
                if zone["span"] > 1:
                    ws.merge_cells(start_row=1, start_column=col, end_row=1,
                                   end_column=col + zone["span"] - 1)
                cell.fill = PatternFill("solid", fgColor=ZONE_FILLS.get(zone["zone_id"], "777777"))
                cell.font = Font(bold=True, color="FFFFFF")
                cell.alignment = Alignment(horizontal="center")
            col += zone["span"]
        ws.cell(row=2, column=1, value="Navn på ansatt")
        for j, c in enumerate(cols, start=2):
            ws.cell(row=2, column=j, value=c["label"])
        ws.cell(row=2, column=len(cols) + 2, value="Stilling")
        for i, person in enumerate(rows, start=3):
            ws.cell(row=i, column=1, value=person["full_name"])
            for j, c in enumerate(cols, start=2):
                status = person["values"].get(c["key"], "")
                ws.cell(row=i, column=j, value=word(status) if status else None)
            ws.cell(row=i, column=len(cols) + 2, value=person["title"])

    ws = wb.create_sheet(MAIN_SHEET)
    fill_grid(ws, with_style=True)
    last_row = len(rows) + 2
    last_col = get_column_letter(len(cols) + 1)
    bold = Font(bold=True)
    for j in range(1, len(cols) + 3):
        header = ws.cell(row=2, column=j)
        header.font = bold
        header.alignment = Alignment(textRotation=90 if 1 < j <= len(cols) + 1 else 0,
                                     vertical="bottom", horizontal="center", wrap_text=True)
    ws.row_dimensions[2].height = 160
    ws.column_dimensions["A"].width = 34
    for j in range(2, len(cols) + 2):
        ws.column_dimensions[get_column_letter(j)].width = 8.5
    ws.column_dimensions[get_column_letter(len(cols) + 2)].width = 28
    if rows:
        area = f"B3:{last_col}{last_row}"
        dv = DataValidation(type="list", formula1='"Ja,Ukjent"', allow_blank=True,
                            showErrorMessage=True, errorTitle="Ugyldig verdi",
                            error="Velg Ja, Ukjent eller la cellen stå tom.")
        ws.add_data_validation(dv)
        dv.add(area)
        ws.conditional_formatting.add(area, CellIsRule(operator="equal", formula=['"Ja"'],
                                      fill=PatternFill("solid", fgColor="CDE8D6")))
        ws.conditional_formatting.add(area, CellIsRule(operator="equal", formula=['"Ukjent"'],
                                      fill=PatternFill("solid", fgColor="F7DFA6")))
        for row in ws.iter_rows(min_row=3, max_row=last_row, min_col=2, max_col=len(cols) + 1):
            for cell in row:
                cell.protection = Protection(locked=False)
                cell.alignment = Alignment(horizontal="center")
    ws.freeze_panes = "B3"
    ws.protection.sheet = True
    ws.protection.formatColumns = False
    ws.protection.formatRows = False
    wb.active = wb.index(ws)

    base = wb.create_sheet(BASE_SHEET)
    fill_grid(base, with_style=False)
    base.sheet_state = "veryHidden"

    buffer = io.BytesIO()
    wb.save(buffer)
    applog.write(conn, "kompetanse", f"Utfyllingsskjema lastet ned ({len(rows)} ansatte).")
    return buffer.getvalue()
